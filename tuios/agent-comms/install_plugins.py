"""Install the local adapters; never modify tool permissions or hook trust."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent
MARKER = "// Generated by agent-comms/install_plugins.py; rerun after moving the checkout."


def install_opencode(config_dir):
    target = config_dir / "plugins/agent-comms"
    target.mkdir(parents=True, exist_ok=True)
    entry = target / "index.js"
    if any(target.iterdir()) and (not entry.exists() or not entry.read_text(encoding="utf-8").startswith(MARKER)):
        raise RuntimeError(f"Refusing to overwrite an unrelated plugin: {target}")
    source = (ROOT / "plugins/opencode/index.js").as_uri()
    entry.write_text(f"{MARKER}\nexport {{ default }} from {json.dumps(source)};\n", encoding="utf-8")
    (target / "package.json").write_text(json.dumps({
        "name": "opencode-agent-comms-local", "private": True, "type": "module",
    }, indent=2) + "\n", encoding="utf-8")
    print(f"OpenCode V2 loader installed: {target}")


def codex(*args):
    result = subprocess.run(["codex", "plugin", *args], capture_output=True, encoding="utf-8", check=True)
    return json.loads(result.stdout)


def install_codex():
    entries = codex("marketplace", "list", "--json")["marketplaces"]
    existing = next((item for item in entries if item["name"] == "agent-comms-local"), None)
    if existing is not None:
        if Path(existing["root"]).resolve() != ROOT:
            raise RuntimeError("agent-comms-local already refers to another checkout; review it before replacing.")
    else:
        subprocess.run(["codex", "plugin", "marketplace", "add", str(ROOT)], check=True)
    result = codex("add", "agent-comms@agent-comms-local", "--json")
    # Print only the installation acknowledgement, not arbitrary hook output.
    print("Codex plugin installed:", json.dumps(result))
    print("In Codex, open /hooks and review/trust the agent-comms SessionStart hook.")
    print("Hook trust was NOT modified by this installer.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", choices=("opencode", "codex"))
    parser.add_argument("--opencode-dir", type=Path,
                        default=Path(os.environ.get("XDG_CONFIG_HOME", Path.home() / ".config")) / "opencode")
    args = parser.parse_args()
    try:
        if args.only != "codex":
            install_opencode(args.opencode_dir.expanduser().resolve())
        if args.only != "opencode":
            install_codex()
    except (OSError, ValueError, RuntimeError, subprocess.SubprocessError) as exc:
        print(f"Plugin install failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
